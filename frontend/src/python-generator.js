import { pythonGenerator, Order } from "blockly/python";

export function registerPythonGenerators() {
  pythonGenerator.forBlock["lab_kafka_setup"] = (block) => {
    const broker = block.getFieldValue("BROKER").replace(/\\/g, "\\\\").replace(/'/g, "\\'");
    pythonGenerator.definitions_["import_json"] = "import json";
    pythonGenerator.definitions_["import_time"] = "import time";
    pythonGenerator.definitions_["import_producer"] = "from confluent_kafka import Producer";
    pythonGenerator.definitions_["kafka_producer"] =
      `producer = Producer({"bootstrap.servers": '${broker}'})`;
    return "";
  };

  pythonGenerator.forBlock["lab_event"] = (block) => {
    const station = JSON.stringify(block.getFieldValue("STATION"));
    const pm25 = Number(block.getFieldValue("PM25"));
    const temp = Number(block.getFieldValue("TEMP"));
    return [`{"station_id": ${station}, "pm25": ${pm25}, "temperature_c": ${temp}}`, Order.ATOMIC];
  };

  pythonGenerator.forBlock["lab_kafka_publish"] = (block, generator) => {
    const event = generator.valueToCode(block, "EVENT", Order.NONE) ||
      '{"station_id": "A01", "pm25": 18.4, "temperature_c": 27.1}';
    const topic = block.getFieldValue("TOPIC").replace(/\\/g, "\\\\").replace(/'/g, "\\'");
    pythonGenerator.definitions_["delivery_callback"] =
      `def delivery_report(error, message):
    if error is not None:
        print(f"Delivery failed: {error}")
    else:
        print(f"Delivered to {message.topic()} partition {message.partition()} offset {message.offset()}")`;
    return `event = {**${event}, "event_time": __import__("datetime").datetime.now(__import__("datetime").timezone.utc).isoformat()}
producer.produce('${topic}', key=event["station_id"], value=json.dumps(event), callback=delivery_report)
producer.poll(0)
print("Queued:", event)
`;
  };

  pythonGenerator.forBlock["lab_repeat"] = (block, generator) => {
    const count = Math.max(1, Math.min(100, Number(block.getFieldValue("COUNT")) || 1));
    const body = generator.statementToCode(block, "DO");
    return `for _ in range(${count}):
${body || "    pass\\n"}`;
  };

  pythonGenerator.forBlock["lab_pause"] = (block) => {
    const seconds = Math.max(0, Math.min(60, Number(block.getFieldValue("SECONDS")) || 0));
    return `time.sleep(${seconds})\\n`;
  };
}

export function generatePython(workspace) {
  const body = pythonGenerator.workspaceToCode(workspace);
  const prefix = [
    '"""Generated by ETL Kafka Blocks Lab. Educational example."""',
    "",
    "# The Kafka broker must be running before executing this file.",
  ].join("\\n");
  const suffix = [
    "",
    "producer.flush(10)",
    "",
  ].join("\\n");
  return `${prefix}\\n\\n${pythonGenerator.definitions_(Object.keys(pythonGenerator.definitions_).sort())}\\n\\n${body}${suffix}`;
}
